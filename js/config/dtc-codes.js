// 2文字目が 0（P0/C0/B0/U0）や P2・P34〜P39 は共通、P1・P30〜P33 などはメーカー独自
export function isGenericCode(code) {
  const t = code[0], d = code[1];
  if (d === '0') return true;
  if (t === 'P' && d === '2') return true;
  if (t === 'P' && d === '3') return Number(code[2]) >= 4;
  if (t === 'U' && d === '3') return true;
  return false;
}
